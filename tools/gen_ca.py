"""Generate src/ca_certs.h: the root CAs the board trusts for firmware updates.

Pulled from Mozilla's trust store (certifi). GitHub currently chains to
Sectigo/USERTrust (github.com) and Let's Encrypt/ISRG (release downloads);
a few other long-lived roots are included so a CA switch doesn't strand updates.

Usage: py -3.12 tools/gen_ca.py
"""
import pathlib
import re
import ssl
import tempfile
import os

import certifi

WANTED = [
    "Sectigo Public Server Authentication Root E46",
    "Sectigo Public Server Authentication Root R46",
    "USERTrust ECC Certification Authority",
    "USERTrust RSA Certification Authority",
    "ISRG Root X1",
    "ISRG Root X2",
    "DigiCert Global Root G2",
    "DigiCert Global Root CA",
]


def common_name(pem):
    f = tempfile.NamedTemporaryFile("w", delete=False, suffix=".pem")
    f.write(pem)
    f.close()
    try:
        info = ssl._ssl._test_decode_cert(f.name)
    finally:
        os.unlink(f.name)
    return dict(x[0] for x in info["subject"]).get("commonName"), info["notAfter"]


bundle = pathlib.Path(certifi.where()).read_text()
pems = re.findall(r"-----BEGIN CERTIFICATE-----.+?-----END CERTIFICATE-----\n", bundle, re.S)

found = {}
for pem in pems:
    cn, expires = common_name(pem)
    if cn in WANTED and cn not in found:
        found[cn] = (pem, expires)

missing = [cn for cn in WANTED if cn not in found]
if missing:
    print("WARNING: not in certifi bundle:", ", ".join(missing))

out = ["// Generated by tools/gen_ca.py - root CAs trusted for firmware updates.", "#pragma once", "",
       "static const char OTA_ROOT_CAS[] ="]
for cn in WANTED:
    if cn not in found:
        continue
    pem, expires = found[cn]
    out.append(f"    // {cn} (expires {expires})")
    out.extend(f'    "{line}\\n"' for line in pem.strip().splitlines())
out[-1] += ";"
path = pathlib.Path(__file__).resolve().parent.parent / "src" / "ca_certs.h"
path.write_text("\n".join(out) + "\n")
print(f"wrote {path} with {len(found)} roots:")
for cn in WANTED:
    if cn in found:
        print(f"  {cn}  (expires {found[cn][1]})")
